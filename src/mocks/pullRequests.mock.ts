import type {
  ConflictRisk,
  PullRequest,
  PullRequestGrade,
  PullRequestStatus,
  PullRequestVisibility,
} from '@/features/pull-request/pullRequest.types';

type PullRequestSeed = {
  id: string;
  repositoryId: string;
  authorId: string;
  title: string;
  originalContent: string;
  contributionTypes: string[];
  coreIdea: string;
  relatedCharacters: string[];
  relatedWorldRules: string[];
  relatedLocations: string[];
  expectedEffect: string;
  conflictRisk: ConflictRisk;
  scores: [number, number, number, number, number];
  grade: PullRequestGrade;
  rationale: string;
  finalGrade?: PullRequestGrade;
  authorGradingNote?: string;
  visibility: PullRequestVisibility;
  status: PullRequestStatus;
  submittedAt: string | null;
  firstViewedByAuthorAt: string | null;
  mergedAt: string | null;
  rejectReason?: string | null;
};

const makePullRequest = (seed: PullRequestSeed): PullRequest => {
  const [scope, permanence, cascade, alignment, specificity] = seed.scores;
  const totalScore = scope + permanence + cascade + alignment + specificity;

  return {
    id: seed.id,
    repositoryId: seed.repositoryId,
    authorId: seed.authorId,
    title: seed.title,
    originalContent: seed.originalContent,
    attachments: [],
    contributionTypes: seed.contributionTypes,
    structuredContent: {
      coreIdea: seed.coreIdea,
      relatedCharacters: seed.relatedCharacters,
      relatedWorldRules: seed.relatedWorldRules,
      relatedLocations: seed.relatedLocations,
      expectedEffect: seed.expectedEffect,
      conflictRisk: seed.conflictRisk,
    },
    aiGrading: {
      scope,
      permanence,
      cascade,
      alignment,
      specificity,
      totalScore,
      grade: seed.grade,
      rationale: seed.rationale,
    },
    contributorOpinion: seed.status === 'DRAFT' ? null : {
      agreesWithAI: true,
      note: 'AI 분석의 방향에 동의합니다. 원작자 검토 시 필요한 부분은 조정해도 괜찮습니다.',
    },
    finalGrade: seed.finalGrade ?? seed.grade,
    authorGradingNote: seed.authorGradingNote ?? '',
    visibility: seed.visibility,
    status: seed.status,
    timestamps: {
      draftStartedAt: '2026-04-18T10:00:00.000Z',
      submittedAt: seed.submittedAt,
      firstViewedByAuthorAt: seed.firstViewedByAuthorAt,
      viewLogs: seed.firstViewedByAuthorAt
        ? [{ viewerId: 'user-ara', viewedAt: seed.firstViewedByAuthorAt }]
        : [],
      mergedAt: seed.mergedAt,
    },
    rejectReason: seed.rejectReason ?? null,
  };
};

